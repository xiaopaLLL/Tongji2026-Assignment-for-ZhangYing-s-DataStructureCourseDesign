#include "T4.h"

// ============================== 主函数 ==============================
int main() {
  QueensGame queens;

  queens.printRule();             // 打印题目说明
  queens.readCount();             // 读入皇后个数 N
  queens.solve();                 // 回溯法求出全部摆法并逐个输出棋盘
  queens.printSolutionCount();    // 输出“共有N种解法!”

  system("pause");

  return 0;
}
