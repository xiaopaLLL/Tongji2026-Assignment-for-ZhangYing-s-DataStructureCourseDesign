#include "T3.h"

// ============================== 主函数 ==============================
int main() {
  Maze maze;

  maze.build();             // 读入地图大小、地图、入口与出口
  maze.search();            // 回溯法搜索通路（栈里保存每个点的下标与方向）
  maze.printMap();          // 输出迷宫地图，走过的点显示为 x
  maze.printPath();         // 输出 <行,列> ---> <行,列> 形式的通路

  system("pause");

  return 0;
}
