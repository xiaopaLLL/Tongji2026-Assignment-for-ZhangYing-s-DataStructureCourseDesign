// ============================================================================
#include "T2.h"

// ============================== 主函数 ==============================
int main() {
  JosephusGame game;

  game.printRule();       // 打印游戏规则
  game.readParameters();  // 读入旅客人数 N、开始位置 S、死亡数字 M、剩余人数 K
  game.buildRing();       // 把 1~N 号旅客尾插成单循环链表
  game.play();            // 从第 S 号开始报数，报到第 M 个人就出局
  game.printDead();       // 按顺序输出每个死者的位置
  game.printSurvivors();  // 输出剩余的生者人数与位置

  system("pause");

  return 0;
}
